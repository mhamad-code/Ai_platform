/**
 * Integration catalogue — 50 developer-facing services.
 *
 * `auth` says how a connection is really established for that vendor:
 *  - 'oauth'  : official authorization-code sign-in (PKCE when supported).
 *               The gateway holds client_id/client_secret and stores the token.
 *  - 'token'  : the vendor only offers API keys / personal access tokens, so
 *               the token is pasted once, validated against the vendor API and
 *               stored encrypted on the gateway.
 *  - 'manual' : the vendor needs account-owner credentials or an admin-approved
 *               OAuth app before anything can work. We show the exact steps
 *               instead of pretending the integration is live.
 */

export type IntegrationCategory = 'git' | 'build' | 'design' | 'data' | 'ops';
export type IntegrationAuth = 'oauth' | 'token' | 'manual';

export interface IntegrationService {
  id: string;
  name: string;
  category: IntegrationCategory;
  color: string;
  icon: string;
  desc: string;
  descAr: string;
  auth: IntegrationAuth;
  docs: string;
  /** OAuth scopes requested by the gateway (only for auth === 'oauth'). */
  scopes?: string[];
  /** Set when the vendor supports PKCE for public clients. */
  pkce?: boolean;
  /** For auth === 'token': the exact credential name the vendor issues. */
  tokenLabel?: string;
  /** For auth === 'manual': ordered setup instructions. */
  setup?: string[];
  /** What the assistant is allowed to do once connected. */
  tools: { id: string; desc: string; descAr: string; sensitive?: boolean }[];
}

